"""Telecom network inventory: sites, equipment, cards, ports and links, with history (Task 9c).

The reference is a network inventory (the system it models manages a few tens of millions of
devices).  The graph is generated by pure functions of the ids, so every answer can be checked
against the model without holding the model in memory:

* ``S`` sites (``region = s % 20``); 10 equipment per site; 10 cards per equipment; 8-48 ports per
  card (``nports``: a hash of the card id); port id ``card * 64 + i``;
* links: port ``i`` of card ``c`` is linked when ``i`` is even, to port ``i`` of the card ``sigma(c)``
  (same equipment slot and card slot, partner site ``(7 j + 3 - s) mod S`` for equipment slot
  ``j``: an involution, so a link joins two sites) when that card has the port and the partner
  site differs: about half the ports, each link connecting two;
* cross-connects: a linked port's ``xc`` is port ``i`` of the same card slot in the next equipment
  of its site, when that port exists and is linked, so a path trace wanders across sites;
* "objects" counts every persisted node: sites + equipment + cards + ports + links.

ProtoDB: one :class:`~proto_db.Dictionary` per type keyed by id, values :class:`~proto_db.DBObject`,
an :class:`~proto_db.EqualityIndex` on each parent reference (``sites.region``,
``equipment.site``, ``cards.equipment``, ``ports.card``), a :class:`~proto_db.FileStorage` with
``durability="fsync"``.  SQLite: the same five tables with primary keys and the same four
indexes, WAL with ``synchronous=FULL``; history in ``equipment_audit``, kept by a trigger on
status updates and stamped with a version counter, so an "as of" query does the equal work of
undoing later changes (ProtoDB reads the earlier root itself: :meth:`Database.snapshot_at`).
Both are built the same way: one transaction per site (its equipment, cards, ports and the
links whose lower port it holds).

Operations, each verified against the model in every repetition:

* point lookup of a port by id (one transaction per request);
* all equipment at a site (the ``site`` index);
* all ports at a site (site -> equipment -> cards -> ports: three index levels; a 3-way join);
* path trace: from a linked port, follow link -> far port -> cross-connect, up to 16 hops
  (ProtoDB: dictionary reads; SQLite: a recursive CTE);
* bulk status change of every equipment of one region (5 % of the sites) in one commit;
* "as of": the status of those equipment in the version before the last bulk change;
* cold against warm: the first point lookup / site query / path trace of a new
  storage instance (ProtoDB) or a new connection (SQLite) against the same requests repeated.
  The OS page cache and the ZFS ARC are not dropped (that needs root): "cold" means empty
  in-process caches.
"""
import os
import random
import time

from benchmarks.harness import BenchResult, benchmark, measure
from benchmarks.support import sqlite_connect

EQ_PER_SITE = 10
CARDS_PER_EQ = 10
REGIONS = 20
MAX_HOPS = 16
OBJECTS_PER_SITE = 3_611            # about: 1 + 10 + 100 + ~2,800 ports + ~700 links (exact count computed)


class Model:
    """The inventory graph as pure functions of the ids (module docstring)."""

    def __init__(self, sites: int):
        self.sites = sites

    @staticmethod
    def nports(card: int) -> int:
        return 8 + ((card * 2654435761) >> 7) % 41

    @staticmethod
    def port_id(card: int, i: int) -> int:
        return card * 64 + i

    @staticmethod
    def card_of_port(pid: int) -> tuple:
        return pid // 64, pid % 64

    def split(self, card: int) -> tuple:
        """``(site, equipment slot, card slot)`` of ``card``."""
        eq = card // CARDS_PER_EQ
        return eq // EQ_PER_SITE, eq % EQ_PER_SITE, card % CARDS_PER_EQ

    def card(self, site: int, j: int, k: int) -> int:
        return (site * EQ_PER_SITE + j) * CARDS_PER_EQ + k

    def partner_card(self, card: int):
        s, j, k = self.split(card)
        ps = (7 * j + 3 - s) % self.sites
        return None if ps == s else self.card(ps, j, k)

    def partner(self, pid: int):
        """The port at the other end of ``pid``'s link, or ``None``."""
        c, i = self.card_of_port(pid)
        if i % 2 or i >= self.nports(c):
            return None
        pc = self.partner_card(c)
        if pc is None or i >= self.nports(pc):
            return None
        return self.port_id(pc, i)

    def xc(self, pid: int):
        """The cross-connect of a linked port: same card slot, next equipment of its site."""
        if self.partner(pid) is None:
            return None
        c, i = self.card_of_port(pid)
        s, j, k = self.split(c)
        q = self.port_id(self.card(s, (j + 1) % EQ_PER_SITE, k), i)
        return q if self.partner(q) is not None else None

    def ports_of_card(self, card: int) -> range:
        return range(self.port_id(card, 0), self.port_id(card, self.nports(card)))

    def cards_of_site(self, site: int):
        for j in range(EQ_PER_SITE):
            for k in range(CARDS_PER_EQ):
                yield self.card(site, j, k)

    def ports_of_site(self, site: int) -> list:
        return [p for c in self.cards_of_site(site) for p in self.ports_of_card(c)]

    def equipment_of_site(self, site: int) -> list:
        return [site * EQ_PER_SITE + j for j in range(EQ_PER_SITE)]

    def sites_of_region(self, region: int) -> list:
        return list(range(region, self.sites, REGIONS))

    def links_of_site(self, site: int) -> list:
        """``(link id, a, b)`` for the links whose lower port is at ``site`` (link id = lower port)."""
        out = []
        for p in self.ports_of_site(site):
            q = self.partner(p)
            if q is not None and p < q:
                out.append((p, p, q))
        return out

    def path(self, start: int) -> list:
        """The port ids a trace from ``start`` visits (module docstring)."""
        out, seen, p = [start], {start}, start
        for _ in range(MAX_HOPS):
            q = self.partner(p)
            if q is None or q in seen:
                break
            out.append(q)
            seen.add(q)
            p = self.xc(q)
            if p is None or p in seen:
                break
            out.append(p)
            seen.add(p)
        return out

    def objects(self) -> int:
        return sum(1 + EQ_PER_SITE + EQ_PER_SITE * CARDS_PER_EQ + len(self.ports_of_site(s)) + len(self.links_of_site(s))
                   for s in range(self.sites))


def site_rows(m: Model, s: int) -> dict:
    """The rows of site ``s`` (one build transaction): tuples in table column order."""
    eqs = [(e, s, f"model-{e % 7}", "in-service", f"SN{e:010d}") for e in m.equipment_of_site(s)]
    cards = [(c, c // CARDS_PER_EQ, c % CARDS_PER_EQ, f"type-{c % 5}") for c in m.cards_of_site(s)]
    ports = [(p, p // 64, p % 64, "up", (min(p, m.partner(p)) if m.partner(p) is not None else None), m.xc(p))
             for p in m.ports_of_site(s)]
    return {"site": (s, f"site-{s}", s % REGIONS), "equipment": eqs, "cards": cards, "ports": ports,
            "links": [(lid, a, b, "fiber") for lid, a, b in m.links_of_site(s)]}


# -- ProtoDB ----------------------------------------------------------------------------------

class ProtoInventory:
    """The ProtoDB copy (module docstring)."""

    ROOTS = ("sites", "equipment", "cards", "ports", "links")

    def __init__(self, path: str):
        from proto_db import FileStorage, ObjectSpace
        self.location = path
        self.space = ObjectSpace(FileStorage(path, durability="fsync"))

    def create(self):
        from proto_db import EqualityIndex
        db = self.space.new_database("inv")

        def init(tr):
            tr.set_root_object("sites", tr.new_dictionary().add_index(EqualityIndex("by_region", "region")))
            tr.set_root_object("equipment", tr.new_dictionary().add_index(EqualityIndex("by_site", "site")))
            tr.set_root_object("cards", tr.new_dictionary().add_index(EqualityIndex("by_equipment", "equipment")))
            tr.set_root_object("ports", tr.new_dictionary().add_index(EqualityIndex("by_card", "card")))
            tr.set_root_object("links", tr.new_dictionary())
        db.run(init)
        self.db = db

    def open(self):
        self.db = self.space.open_database("inv")

    def add_site(self, rows: dict) -> None:
        def fn(tr):
            sites = tr.get_root_object("sites")
            s, name, region = rows["site"]
            tr.set_root_object("sites", sites.set_at(s, tr.new_object(id=s, name=name, region=region)))
            d = tr.get_root_object("equipment")
            for e, site, model, status, serial in rows["equipment"]:
                d = d.set_at(e, tr.new_object(id=e, site=site, model=model, status=status, serial=serial))
            tr.set_root_object("equipment", d)
            d = tr.get_root_object("cards")
            for c, eq, slot, kind in rows["cards"]:
                d = d.set_at(c, tr.new_object(id=c, equipment=eq, slot=slot, type=kind))
            tr.set_root_object("cards", d)
            d = tr.get_root_object("ports")
            for p, card, idx, status, link, xc in rows["ports"]:
                d = d.set_at(p, tr.new_object(id=p, card=card, idx=idx, status=status, link=link, xc=xc))
            tr.set_root_object("ports", d)
            d = tr.get_root_object("links")
            for lid, a, b, kind in rows["links"]:
                d = d.set_at(lid, tr.new_object(id=lid, a=a, b=b, kind=kind))
            tr.set_root_object("links", d)
        self.db.run(fn, retries=1)

    @staticmethod
    def _by(view, root: str, field: str, value) -> list:
        from proto_db import F, from_collection
        return list(from_collection(view.get_root_object(root)).where(getattr(F, field) == value))

    def port(self, pid: int) -> tuple:
        tr = self.db.new_transaction()
        try:
            p = tr.get_root_object("ports").get_at(pid)
            return (p.id, p.card, p.idx, p.status, p.link, p.xc)
        finally:
            tr.abort()

    def site_equipment(self, site: int, view=None) -> list:
        tr = view or self.db.new_transaction()
        try:
            return sorted((e.id, e.status) for e in self._by(tr, "equipment", "site", site))
        finally:
            if view is None:
                tr.abort()

    def site_ports(self, site: int) -> list:
        tr = self.db.new_transaction()
        try:
            out = []
            for e in self._by(tr, "equipment", "site", site):
                for c in self._by(tr, "cards", "equipment", e.id):
                    out.extend(p.id for p in self._by(tr, "ports", "card", c.id))
            return sorted(out)
        finally:
            tr.abort()

    def path(self, start: int) -> list:
        tr = self.db.new_transaction()
        try:
            ports, links = tr.get_root_object("ports"), tr.get_root_object("links")
            out, seen, p = [start], {start}, start
            for _ in range(MAX_HOPS):
                rec = ports.get_at(p)
                if rec.link is None:
                    break
                link = links.get_at(rec.link)
                q = link.b if link.a == p else link.a
                if q in seen:
                    break
                out.append(q)
                seen.add(q)
                nxt = ports.get_at(q).xc
                if nxt is None or nxt in seen:
                    break
                out.append(nxt)
                seen.add(nxt)
                p = nxt
            return out
        finally:
            tr.abort()

    def bulk_status(self, sites: list, status: str) -> bytes:
        """Set the status of every equipment of ``sites`` in one commit; return the reference of
        the version it replaced (for the "as of" query)."""
        box = {}

        def fn(tr):
            box["before"] = tr.snapshot_ref
            d = tr.get_root_object("equipment")
            for s in sites:
                for e in self._by(tr, "equipment", "site", s):
                    d = d.set_at(e.id, e.with_(status=status))
            tr.set_root_object("equipment", d)
        self.db.run(fn, retries=1)
        return box["before"]

    def as_of(self, ref: bytes, sites: list) -> list:
        snap = self.db.snapshot_at(ref)
        return sorted(x for s in sites for x in self.site_equipment(s, view=snap))

    def close(self):
        self.space.close()


# -- SQLite -----------------------------------------------------------------------------------

SQL_SCHEMA = """
CREATE TABLE site (id INTEGER PRIMARY KEY, name TEXT, region INTEGER);
CREATE TABLE equipment (id INTEGER PRIMARY KEY, site INTEGER, model TEXT, status TEXT, serial TEXT);
CREATE TABLE card (id INTEGER PRIMARY KEY, equipment INTEGER, slot INTEGER, type TEXT);
CREATE TABLE port (id INTEGER PRIMARY KEY, card INTEGER, idx INTEGER, status TEXT, link INTEGER, xc INTEGER);
CREATE TABLE link (id INTEGER PRIMARY KEY, a INTEGER, b INTEGER, kind TEXT);
CREATE INDEX site_region ON site(region);
CREATE INDEX equipment_site ON equipment(site);
CREATE INDEX card_equipment ON card(equipment);
CREATE INDEX port_card ON port(card);
CREATE TABLE meta (version INTEGER);
INSERT INTO meta VALUES (0);
CREATE TABLE equipment_audit (id INTEGER, version INTEGER, old_status TEXT, new_status TEXT);
CREATE INDEX equipment_audit_id ON equipment_audit(id, version);
CREATE TRIGGER equipment_status_audit AFTER UPDATE OF status ON equipment
BEGIN
  INSERT INTO equipment_audit VALUES (old.id, (SELECT version FROM meta), old.status, new.status);
END;
"""

PATH_SQL = """
WITH RECURSIVE trace(hop, port, far) AS (
  SELECT 0, p.id, CASE WHEN l.a = p.id THEN l.b ELSE l.a END
  FROM port p JOIN link l ON l.id = p.link WHERE p.id = ?
  UNION ALL
  SELECT t.hop + 1, f.xc, CASE WHEN l.a = f.xc THEN l.b ELSE l.a END
  FROM trace t JOIN port f ON f.id = t.far JOIN port n ON n.id = f.xc JOIN link l ON l.id = n.link
  WHERE t.hop < ?
)
SELECT port, far FROM trace ORDER BY hop
"""


class SqlInventory:
    """The SQLite copy (module docstring)."""

    def __init__(self, path: str):
        self.location = path
        self.conn = sqlite_connect(path, "fsync")

    def create(self):
        self.conn.executescript(SQL_SCHEMA)

    def add_site(self, rows: dict) -> None:
        c = self.conn
        c.execute("BEGIN")
        c.execute("INSERT INTO site VALUES (?,?,?)", rows["site"])
        c.executemany("INSERT INTO equipment VALUES (?,?,?,?,?)", rows["equipment"])
        c.executemany("INSERT INTO card VALUES (?,?,?,?)", rows["cards"])
        c.executemany("INSERT INTO port VALUES (?,?,?,?,?,?)", rows["ports"])
        c.executemany("INSERT INTO link VALUES (?,?,?,?)", rows["links"])
        c.execute("COMMIT")

    def port(self, pid: int) -> tuple:
        return self.conn.execute("SELECT id, card, idx, status, link, xc FROM port WHERE id = ?", (pid,)).fetchone()

    def site_equipment(self, site: int) -> list:
        return sorted(self.conn.execute("SELECT id, status FROM equipment WHERE site = ?", (site,)).fetchall())

    def site_ports(self, site: int) -> list:
        return sorted(r[0] for r in self.conn.execute(
            "SELECT p.id FROM equipment e JOIN card c ON c.equipment = e.id JOIN port p ON p.card = c.id "
            "WHERE e.site = ?", (site,)))

    def path(self, start: int) -> list:
        rows = self.conn.execute(PATH_SQL, (start, MAX_HOPS)).fetchall()
        # The CTE yields (port, far port) per hop; the trace stops at the first port seen twice,
        # as the model's does, and after MAX_HOPS links.
        out, seen = [], set()
        for port in [x for row in rows for x in row][:1 + 2 * MAX_HOPS] or [start]:
            if port in seen:
                break
            out.append(port)
            seen.add(port)
        return out

    def bulk_status(self, sites: list, status: str) -> int:
        """One transaction: bump the version, update the status (the trigger audits); return the
        version the change replaced."""
        c = self.conn
        c.execute("BEGIN")
        before = c.execute("SELECT version FROM meta").fetchone()[0]
        c.execute("UPDATE meta SET version = version + 1")
        marks = ",".join("?" * len(sites))
        c.execute(f"UPDATE equipment SET status = ? WHERE site IN ({marks})", (status, *sites))
        c.execute("COMMIT")
        return before

    def as_of(self, version: int, sites: list) -> list:
        marks = ",".join("?" * len(sites))
        return sorted(self.conn.execute(
            "SELECT e.id, COALESCE((SELECT a.old_status FROM equipment_audit a WHERE a.id = e.id AND a.version > ? "
            f"ORDER BY a.version LIMIT 1), e.status) FROM equipment e WHERE e.site IN ({marks})",
            (version, *sites)).fetchall())

    def close(self):
        self.conn.close()


def _settled_du(path: str, timeout: float = 30.0) -> int:
    """:func:`_du` after ``os.sync()`` once it stops changing: ZFS updates the allocated size
    only when its transaction group is written (about every 5 s)."""
    os.sync()
    last, deadline = _du(path), time.monotonic() + timeout
    while time.monotonic() < deadline:
        time.sleep(2.0)
        now = _du(path)
        if now == last and now > 0:
            return now
        last = now
    return last


def _du(path: str) -> int:
    """Bytes allocated on disk under ``path`` (what ``du`` reports: compression included)."""
    total = 0
    if os.path.isfile(path):
        return os.stat(path).st_blocks * 512
    for dirpath, _, files in os.walk(path):
        for f in files:
            total += os.stat(os.path.join(dirpath, f)).st_blocks * 512
    return total


def _apparent(path: str) -> int:
    if os.path.isfile(path):
        return os.path.getsize(path)
    return sum(os.path.getsize(os.path.join(d, f)) for d, _, fs in os.walk(path) for f in fs)


@benchmark("inventory", quick={"objects": 8_000, "requests": 5, "path_requests": 3},
           full={"objects": 100_000, "requests": 100, "path_requests": 20})
def inventory(ctx, p):
    """Telecom inventory graph (sites/equipment/cards/ports/links, history): ProtoDB vs sqlite3."""
    sites = max(2, round(p["objects"] / OBJECTS_PER_SITE))
    m = Model(sites)
    rng = random.Random(9)
    base = ctx.tempdir("inventory")
    t0 = time.perf_counter()
    objects = m.objects()
    result = BenchResult({"sites": sites, "objects": objects, "fan_out": "10 equipment/site, 10 cards/equipment, "
                          "8-48 ports/card, links on about half the ports", "durability": "ProtoDB fsync, SQLite FULL",
                          "model_count_s": round(time.perf_counter() - t0, 2)}, None, None)
    proto = ProtoInventory(os.path.join(base, "protodb"))
    sql = SqlInventory(os.path.join(base, "inventory.sqlite"))
    try:
        # -- build: one transaction per site, both systems, interleaved per site
        proto.create()
        sql.create()
        pt = st = 0.0
        for s in range(sites):
            rows = site_rows(m, s)
            a = time.perf_counter()
            proto.add_site(rows)
            b = time.perf_counter()
            sql.add_site(rows)
            pt += b - a
            st += time.perf_counter() - b
        result.add_timing("protodb build (one commit per site)", [pt], per=objects)
        result.add_timing("sqlite3 build (one transaction per site)", [st], per=objects)
        result.metrics["build commits/s"] = {"protodb": round(sites / pt, 2), "sqlite3": round(sites / st, 2)}
        result.metrics["build objects/s"] = {"protodb": round(objects / pt), "sqlite3": round(objects / st)}
        sql.conn.execute("PRAGMA wal_checkpoint(TRUNCATE)")
        sizes = {"protodb": (_settled_du(proto.location), _apparent(proto.location)),
                 "sqlite3": (_settled_du(sql.location), _apparent(sql.location))}
        result.metrics["on-disk bytes (allocated, apparent)"] = sizes
        result.metrics["bytes per object (allocated, apparent)"] = {
            k: (round(v[0] / objects, 1), round(v[1] / objects, 1)) for k, v in sizes.items()}
        # counts read back
        tr = proto.db.new_transaction()
        got = tuple(tr.get_root_object(r).count for r in ProtoInventory.ROOTS)
        tr.abort()
        sgot = tuple(sql.conn.execute(f"SELECT count(*) FROM {t}").fetchone()[0]
                     for t in ("site", "equipment", "card", "port", "link"))
        result.check("protodb objects == model", sum(got) == objects, f"{got} vs {objects}")
        result.check("sqlite3 rows == model", sum(sgot) == objects and sgot == got, f"{sgot} vs {got}")

        # -- request sets (the same for both systems)
        all_ports = lambda: m.port_id(rng.randrange(sites * 100), 0)  # noqa: E731  (a card's first port)
        port_ids = [all_ports() + rng.randrange(8) for _ in range(p["requests"])]
        site_ids = [rng.randrange(sites) for _ in range(p["requests"])]
        port_sites = site_ids[:max(1, p["requests"] // 20)]
        starts = []
        while len(starts) < p["path_requests"]:
            c = rng.randrange(sites * 100)
            q = m.port_id(c, 2 * rng.randrange(4))
            if m.partner(q) is not None:
                starts.append(q)
        want_ports = [(q, q // 64, q % 64, "up", (min(q, m.partner(q)) if m.partner(q) is not None else None), m.xc(q))
                      for q in port_ids]
        want_eq = [[(e, "in-service") for e in m.equipment_of_site(s)] for s in site_ids]
        want_site_ports = [m.ports_of_site(s) for s in port_sites]
        want_paths = [m.path(q) for q in starts]
        result.work["mean path length (ports)"] = round(sum(map(len, want_paths)) / len(want_paths), 1)
        ops = [("point lookup of a port", "port", port_ids, want_ports),
               ("equipment at a site", "site_equipment", site_ids, want_eq),
               ("ports at a site (3 levels / 3-way join)", "site_ports", port_sites, want_site_ports),
               ("path trace", "path", starts, want_paths)]
        for label, method, args, want in ops:
            for name, sysobj in (("protodb", proto), ("sqlite3", sql)):
                fn = getattr(sysobj, method)
                samples, _ = measure(lambda fn=fn, args=args: [fn(a) for a in args], ctx.repeat, ctx.warmup,
                                     expect=want)
                result.add_timing(f"{name} {label} (warm)", samples, per=len(args))

        # -- cold against warm: a new storage instance / connection per sample
        cold_ops = [("point lookup", "port", port_ids[0], want_ports[0]),
                    ("equipment at a site", "site_equipment", site_ids[0], want_eq[0]),
                    ("path trace", "path", starts[0], want_paths[0])]
        for label, method, arg, want in cold_ops:
            def proto_cold(_, method=method, arg=arg):
                fresh = ProtoInventory(proto.location)
                fresh.open()
                try:
                    return getattr(fresh, method)(arg)
                finally:
                    fresh.close()

            def sql_cold(_, method=method, arg=arg):
                fresh = SqlInventory(sql.location)
                try:
                    return getattr(fresh, method)(arg)
                finally:
                    fresh.close()
            for name, fn in (("protodb", proto_cold), ("sqlite3", sql_cold)):
                samples, _ = measure(fn, ctx.repeat, ctx.warmup, setup=lambda: None, expect=want)
                result.add_timing(f"{name} {label}, cold (first request of a new instance)", samples)
        result.notes.append("cold = a new storage instance or connection (empty in-process caches); the OS page "
                            "cache and the ZFS ARC are not dropped, which needs root")

        # -- bulk status change of one region, then "as of" the version before it
        region_sites = m.sites_of_region(1)
        region_eq = [e for s in region_sites for e in m.equipment_of_site(s)]
        result.work["bulk change: sites, equipment"] = [len(region_sites), len(region_eq)]
        state = {"n": 0, "proto_ref": None, "sql_version": None}

        def statuses(status):
            return sorted((e, status) for e in region_eq)

        for name, sysobj in (("protodb", proto), ("sqlite3", sql)):
            counter = [0]

            def change(sysobj=sysobj, counter=counter, name=name):
                counter[0] += 1
                status = f"maint-{counter[0]}"
                before = sysobj.bulk_status(region_sites, status)
                state[f"{name}_before"] = before
                state[f"{name}_prev"] = "in-service" if counter[0] == 1 else f"maint-{counter[0] - 1}"
                return sorted(x for s in region_sites for x in sysobj.site_equipment(s)) == statuses(status)
            samples, _ = measure(change, ctx.repeat, ctx.warmup, expect=True)
            result.add_timing(f"{name} bulk status change of one region (one commit)", samples, per=len(region_eq))
            want_asof = statuses(state[f"{name}_prev"])
            samples, _ = measure(lambda sysobj=sysobj, name=name: sysobj.as_of(state[f"{name}_before"], region_sites),
                                 ctx.repeat, ctx.warmup, expect=want_asof)
            result.add_timing(f"{name} as-of: region status before the last change", samples, per=len(region_eq))
        audit = sql.conn.execute("SELECT count(*) FROM equipment_audit").fetchone()[0]
        result.check("sqlite3 audit rows == changes made", audit == len(region_eq) * (ctx.repeat + ctx.warmup),
                     f"{audit}")
        sizes_after = {"protodb": _settled_du(proto.location), "sqlite3": _settled_du(sql.location)}
        result.metrics["on-disk bytes after the bulk changes (allocated)"] = sizes_after
        tr = proto.db.new_transaction()
        final = tuple(tr.get_root_object(r).count for r in ProtoInventory.ROOTS)
        tr.abort()
        result.checksum, result.expected = final, got
    finally:
        proto.close()
        sql.close()
    return result
